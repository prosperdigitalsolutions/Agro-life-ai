"""
AGRO LIFE-AI
Research Shelf-Life Prediction Module

Purpose:
Use the final research prototype Random Forest model to
estimate tomato shelf life from Day-4 measurements.

Research model features:
    - weight_loss_day4
    - ta_day4

Important:
This is a research prototype based on the selected tomato
research dataset. Predictions are not independently validated
for commercial agricultural deployment.
"""

from pathlib import Path

import joblib
import pandas as pd


# ============================================================
# PROJECT PATHS
# ============================================================

PROJECT_ROOT = Path(__file__).resolve().parents[2]

MODEL_FILE = (
    PROJECT_ROOT
    / "models"
    / "final_research_shelf_life_model.joblib"
)


# ============================================================
# MODEL FEATURES
# ============================================================

FEATURES = [
    "weight_loss_day4",
    "ta_day4",
]


# ============================================================
# LOAD MODEL
# ============================================================

def load_research_model():
    """
    Load the final trained research model.
    """

    if not MODEL_FILE.exists():
        raise FileNotFoundError(
            f"Final research model not found:\n{MODEL_FILE}"
        )

    return joblib.load(MODEL_FILE)


# ============================================================
# PREDICTION FUNCTION
# ============================================================

def predict_shelf_life(
    weight_loss_day4: float,
    ta_day4: float
) -> float:
    """
    Predict shelf life using Day-4 weight loss and
    titratable acidity.

    Parameters
    ----------
    weight_loss_day4 : float
        Percentage weight loss measured on Day 4.

    ta_day4 : float
        Titratable acidity measured on Day 4.

    Returns
    -------
    float
        Predicted shelf life in days.
    """

    # --------------------------------------------------------
    # Input validation
    # --------------------------------------------------------

    if weight_loss_day4 < 0:
        raise ValueError(
            "Day-4 weight loss cannot be negative."
        )

    if ta_day4 < 0:
        raise ValueError(
            "Day-4 titratable acidity cannot be negative."
        )

    # --------------------------------------------------------
    # Load model
    # --------------------------------------------------------

    model = load_research_model()

    # --------------------------------------------------------
    # Create DataFrame with the SAME feature names used
    # during model training.
    # --------------------------------------------------------

    input_data = pd.DataFrame(
        [[
            weight_loss_day4,
            ta_day4
        ]],
        columns=FEATURES
    )

    # --------------------------------------------------------
    # Generate prediction
    # --------------------------------------------------------

    prediction = model.predict(input_data)[0]

    return float(prediction)


# ============================================================
# TEST FUNCTION
# ============================================================

def main():
    """
    Test the research prediction module.
    """

    print("=" * 70)
    print("AGRO LIFE-AI")
    print("RESEARCH SHELF-LIFE PREDICTION TEST")
    print("=" * 70)

    # --------------------------------------------------------
    # Example research observation
    # --------------------------------------------------------

    weight_loss = 1.43
    titratable_acidity = 0.74

    print("\nInput measurements:")
    print(
        f"  Day-4 Weight Loss: "
        f"{weight_loss:.2f}%"
    )

    print(
        f"  Day-4 Titratable Acidity: "
        f"{titratable_acidity:.2f}%"
    )

    # --------------------------------------------------------
    # Prediction
    # --------------------------------------------------------

    predicted_shelf_life = predict_shelf_life(
        weight_loss,
        titratable_acidity
    )

    print("\nPrediction:")
    print(
        f"  Estimated Shelf Life: "
        f"{predicted_shelf_life:.2f} days"
    )

    # --------------------------------------------------------
    # Research limitation
    # --------------------------------------------------------

    print("\nImportant:")
    print(
        "This prediction is generated by the AGRO LIFE-AI "
        "research prototype and should not be interpreted "
        "as independently validated commercial advice."
    )

    print("\n" + "=" * 70)
    print("RESEARCH PREDICTION TEST COMPLETED")
    print("=" * 70)


# ============================================================
# RUN TEST
# ============================================================

if __name__ == "__main__":
    main()